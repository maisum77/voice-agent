def build() -> list[dict]:
    cells: list[dict] = []

    def md(src: str) -> None:
        cells.append({"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)})

    def code(src: str) -> None:
        cells.append(
            {
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": src.splitlines(keepends=True),
            }
        )

    md(MD_INTRO)
    md(MD_INPUTS)
    code(CODE_INSTALL)
    code(CODE_CONFIG)
    code(CODE_MODULES)
    code(CODE_IMPORT)
    code(CODE_TEST)
    code(CODE_FIND_INPUT)
    code(embed_deepseek() + "\n" + embed_handwritten())
    code(CODE_DATA)
    code(CODE_BASE)
    code(CODE_TEACHER)
    code(CODE_ANNOTATE)
    code(CODE_GATE)
    code(CODE_REVIEW)
    code(CODE_FLATTEN)
    code(CODE_TRAIN)
    code(CODE_EVAL)
    code(CODE_SAVE)
    md(MD_NEXT)
    return cells


def validate(cells: list[dict]) -> None:
    """Every code cell must compile, and the embedded modules must be intact."""
    for i, cell in enumerate(cells):
        if cell["cell_type"] != "code":
            continue
        src = "".join(cell["source"])
        # IPython magics are not Python; blank them out before parsing.
        python = "\n".join(
            ("#" + line[1:]) if line.lstrip()[:1] in ("!", "%") else line
            for line in src.splitlines()
        )
        try:
            ast.parse(python)
        except SyntaxError as exc:
            lines = python.splitlines()
            ln = exc.lineno or 1
            context = "\n".join(
                f"  {j + 1:4d}| {lines[j][:110]}"
                for j in range(max(0, ln - 3), min(len(lines), ln + 2))
            )
            raise SystemExit(f"cell {i} does not compile: {exc}\n{context}")

    # Round-trip: the embedded source must equal the file in the repo.
    for rel, dest in MODULES:
        original = read(rel)
        if original.rstrip("\n") not in original:
            raise SystemExit(f"embedded source for {rel} does not round-trip")


def main() -> int:
    cells = build()
    validate(cells)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    OUT.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    n_code = sum(1 for c in cells if c["cell_type"] == "code")
    print(f"wrote {OUT}  ({len(cells)} cells, {n_code} code)")
    return 0


