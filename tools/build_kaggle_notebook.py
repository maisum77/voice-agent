def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def embed_module(rel: str, dest: str) -> str:
    """A cell that writes one module out verbatim."""
    src = read(rel)
    if "'''" in src:
        raise SystemExit(f"{rel} contains a triple-single-quote; pick another delimiter")
    if src.rstrip("\n").endswith("\\"):
        raise SystemExit(f"{rel} ends with a backslash; a raw string would break")
    return f'''# ---- {rel} -> {dest} -------------------------------------------------
from pathlib import Path as _P
_d = _P(WORK) / "voicepipeline" / "{dest}"
_d.parent.mkdir(parents=True, exist_ok=True)
_d.write_text(r\'\'\'
{src}\'\'\', encoding="utf-8")
print("wrote", _d)
'''


def embed_deepseek() -> str:
    """The DeepSeek dataset, embedded so the notebook needs one input file."""
    raw = (ROOT / "deepseek_companion.jsonl").read_text(encoding="utf-8")
    if "'''" in raw:
        raise SystemExit("deepseek_companion.jsonl contains a triple-single-quote")
    return f'''# The DeepSeek companion set, embedded so the only thing to attach is the
# LoRA zip. It was generated by DeepSeek and is the joyful-register source
# that gets re-registered into the canonical persona.
DEEPSEEK_JSONL = r\'\'\'
{raw}\'\'\'
'''


def embed_handwritten() -> str:
    """The hand-written pairs, extracted from make_joyful_data.py."""
    src = Path.home() / "Downloads" / "make_joyful_data.py"
    if not src.exists():
        return "# make_joyful_data.py not found; the hand-written set is skipped.\n"
    text = src.read_text(encoding="utf-8")
    start = text.index("E = [")
    end = text.index("\nwith open(")
    tree = ast.parse(text[start:end])
    pairs = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == "E":
            pairs = ast.literal_eval(node.value)
    body = json.dumps(pairs, ensure_ascii=False, indent=1)
    if "'''" in body:
        raise SystemExit("hand-written pairs contain a triple-single-quote")
    return f'''# Hand-written pairs, kept alongside the DeepSeek set. Same joyful register,
# same job: they get re-registered into the canonical persona.
HANDWRITTEN_PAIRS = json.loads(r\'\'\'
{body}\'\'\')
'''


